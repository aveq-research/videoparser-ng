#!/usr/bin/env pytest

import json
import os
import subprocess
from typing import Dict, List

import pytest

HERE = os.path.dirname(os.path.realpath(__file__))

# test files and their expected codecs
TEST_FILES = [
    ("test-libaom-av1.mp4", "av1"),
    ("test-libvpx-vp9.mp4", "vp9"),
    ("test-libx264.mp4", "h264"),
    ("test-libx265.mp4", "hevc"),
    ("test-mpeg2video.ts", "mpeg2"),
    ("test-mpeg2video.mpg", "mpeg2"),
]


def run_parser(video_file: str, num_frames: int = 2) -> tuple[List[Dict], Dict, Dict]:
    """Call the video parser on the given video file and return frame info, sequence info and summary."""

    # get stdout only
    output = subprocess.check_output(
        [
            "../build/VideoParserCli/video-parser",
            video_file,
            "-n",  # number of frames to parse
            str(num_frames),
        ],
        cwd=HERE,
    )

    # parse the ldjson output
    frame_info: List[Dict] = []
    sequence_info: Dict = {}
    summary: Dict = {}

    for line in output.decode("utf-8").splitlines():
        json_line = json.loads(line)
        if json_line["type"] == "frame_info":
            frame_info.append(json_line)
        elif json_line["type"] == "sequence_info":
            sequence_info = json_line
        elif json_line["type"] == "summary":
            summary = json_line

    return frame_info, sequence_info, summary


def call_parser(video_file: str, num_frames: int = 2) -> tuple[List[Dict], Dict]:
    """Call the video parser on the given video file and return frame info and sequence info."""
    frame_info, sequence_info, _ = run_parser(video_file, num_frames)
    return frame_info, sequence_info


class TestCLI:
    @pytest.mark.parametrize("test_file,expected_codec", TEST_FILES)
    def test_parser_cli(self, test_file: str, expected_codec: str):
        # Call parser on test file
        frame_info, sequence_info = call_parser(os.path.join(HERE, test_file))

        # Basic validation of output structure
        assert len(frame_info) == 2, "Expected 2 frames of data"
        assert sequence_info, "Expected sequence info"

        # Validate sequence info
        assert sequence_info["video_codec"] == expected_codec
        assert sequence_info["video_width"] > 0
        assert sequence_info["video_height"] > 0
        assert sequence_info["video_framerate"] > 0
        assert sequence_info["video_duration"] > 0
        assert sequence_info["video_frame_count"] > 0

        # Validate frame info for both frames
        for frame in frame_info:
            # Check required fields exist and have valid values
            assert "frame_idx" in frame
            assert "pts" in frame
            assert "dts" in frame
            assert "size" in frame and frame["size"] > 0
            assert "frame_type" in frame
            assert "is_idr" in frame
            assert frame["decode_error"] is False
            assert frame["discontinuity"] is False

            # QP values should exist and be reasonable
            assert "qp_avg" in frame
            assert "qp_min" in frame
            assert "qp_max" in frame
            assert frame["qp_min"] <= frame["qp_avg"] <= frame["qp_max"]

        # First frame should be a keyframe
        assert frame_info[0]["is_idr"] is True
        assert frame_info[0]["frame_idx"] == 0

        # Second frame should have frame_idx 1
        assert frame_info[1]["frame_idx"] == 1

    @pytest.mark.parametrize(
        "test_file", ["test-libx264.mp4", "test-libx265.mp4"]
    )
    def test_parser_cli_flushes_delayed_frames(self, test_file: str):
        frame_info, sequence_info = call_parser(
            os.path.join(HERE, test_file), num_frames=-1
        )

        assert len(frame_info) == sequence_info["video_frame_count"] == 300
        assert frame_info[-1]["frame_idx"] == 299
        assert frame_info[-1]["size"] > 0

    @pytest.mark.parametrize("test_file,_", TEST_FILES)
    @pytest.mark.parametrize("num_frames", [2, -1])
    def test_parser_cli_summary(self, test_file: str, _, num_frames: int):
        frame_info, _, summary = run_parser(os.path.join(HERE, test_file), num_frames)

        assert summary["frame_count"] == len(frame_info)
        assert summary["decode_errors"] == 0
        assert summary["corrupt_packets"] == 0
        assert summary["discontinuities"] == 0

    # Two 2-second parts at 25 fps, joined with a timestamp jump (generated by
    # util/generate-damaged-test-videos.py)
    @pytest.mark.parametrize(
        "test_file", ["test-libx264-pts-jump.ts", "test-libx264-pts-backwards.ts"]
    )
    def test_parser_cli_discontinuity(self, test_file: str):
        frame_info, sequence_info, summary = run_parser(
            os.path.join(HERE, test_file), num_frames=-1
        )

        assert len(frame_info) == 100
        assert [f["frame_idx"] for f in frame_info if f["discontinuity"]] == [50]
        assert summary["discontinuities"] == 1

        # Duration and bitrate without the gap
        assert sequence_info["video_duration"] == pytest.approx(4.0)
        video_bytes = sum(f["size"] for f in frame_info)
        assert sequence_info["video_bitrate"] == pytest.approx(
            video_bytes * 8 / 1000 / 4.0
        )

    # Interlaced and soft-telecine clips (generated by
    # util/generate-interlaced-test-videos.sh)
    @pytest.mark.parametrize(
        "test_file,field_order",
        [
            ("test-mpeg2video-tff.ts", "tt"),
            ("test-mpeg2video-bff.ts", "bb"),
            ("test-libx264-tff.ts", "tt"),
            ("test-libx264-bff.ts", "bb"),
        ],
    )
    def test_parser_cli_interlaced(self, test_file: str, field_order: str):
        frame_info, sequence_info, summary = run_parser(
            os.path.join(HERE, test_file), num_frames=-1
        )

        assert len(frame_info) == 50
        assert sequence_info["video_interlaced"] is True
        assert sequence_info["video_field_order"] == field_order
        assert sequence_info["video_framerate"] == 25.0
        for frame in frame_info:
            assert frame["interlaced"] is True
            assert frame["top_field_first"] is (field_order == "tt")
            assert frame["repeated_fields"] == 0
        assert summary["interlaced_frames"] == 50
        assert summary["repeated_fields"] == 0

    @pytest.mark.parametrize("test_file,_", TEST_FILES)
    def test_parser_cli_progressive(self, test_file: str, _):
        frame_info, sequence_info, summary = run_parser(
            os.path.join(HERE, test_file), num_frames=-1
        )

        assert sequence_info["video_interlaced"] is False
        assert sequence_info["video_field_order"] == "progressive"
        assert not any(f["interlaced"] for f in frame_info)
        assert summary["interlaced_frames"] == 0
        assert summary["repeated_fields"] == 0

    def test_parser_cli_soft_telecine(self):
        frame_info, sequence_info, summary = run_parser(
            os.path.join(HERE, "test-mpeg2video-pulldown.ts"), num_frames=-1
        )

        # 48 frames at 23.976 fps, displayed as 60 frames at 29.97 fps: every
        # second frame repeats its first field
        assert len(frame_info) == 48
        assert sequence_info["video_interlaced"] is False
        assert sequence_info["video_field_order"] == "progressive"
        assert sequence_info["video_framerate"] == pytest.approx(30000 / 1001)
        assert [f["repeated_fields"] for f in frame_info] == [1, 0] * 24
        assert not any(f["interlaced"] for f in frame_info)
        assert summary["interlaced_frames"] == 0
        assert summary["repeated_fields"] == 24
        assert 2 * len(frame_info) + summary["repeated_fields"] == 120

    def test_parser_cli_field_pairs(self):
        video_file = os.path.join(HERE, "test-h264-paff.264")
        frame_info, sequence_info, summary = run_parser(video_file, num_frames=-1)

        # 30 field pictures, decoded as 15 frames; each frame has the size of
        # both fields
        assert len(frame_info) == 15
        assert sequence_info["video_interlaced"] is True
        assert sequence_info["video_field_order"] == "tt"
        assert summary["interlaced_frames"] == 15
        assert frame_info[0]["size"] == 21791 + 8958
        assert sum(f["size"] for f in frame_info) == os.path.getsize(video_file)

    def test_parser_cli_timestamp_wrap(self):
        frame_info, sequence_info, summary = run_parser(
            os.path.join(HERE, "test-libx264-pts-wrap.ts"), num_frames=-1
        )

        assert len(frame_info) == 50
        assert sequence_info["video_duration"] == pytest.approx(2.0)
        assert summary["discontinuities"] == 0

    def test_parser_cli_decode_errors(self):
        frame_info, _, summary = run_parser(
            os.path.join(HERE, "test-libx264-bitflip.ts"), num_frames=-1
        )

        assert len(frame_info) == 50
        errors = sum(f["decode_error"] for f in frame_info)
        assert 0 < errors < 50
        assert summary["decode_errors"] == errors

    def test_parser_cli_unknown_pixel_format(self):
        # The PMT declares the H.264 stream as MPEG-2
        result = subprocess.run(
            [
                "../build/VideoParserCli/video-parser",
                os.path.join(HERE, "test-libx264-pmt-mpeg2.ts"),
            ],
            cwd=HERE,
            capture_output=True,
            text=True,
        )

        assert result.returncode == 1
        assert result.stdout == ""
        assert "Cannot determine the video format" in result.stderr
